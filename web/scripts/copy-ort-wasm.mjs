// onnxruntime-web loads its WASM binary at runtime by URL. Next.js will not
// bundle it, so it is copied into public/ and ort.env.wasm.wasmPaths is pointed
// at that directory. Runs on postinstall so it can never drift from the
// installed onnxruntime-web version.
//
// The binary goes into a VERSIONED directory, and lib/ort-version.ts is
// generated to match. That is what lets the deploy headers cache it as
// `immutable` for a year: the filename alone is constant across releases, so
// without the version in the path, upgrading onnxruntime-web would leave
// returning visitors running new JS against a year-old cached binary.
import {
  mkdirSync,
  readdirSync,
  copyFileSync,
  existsSync,
  readFileSync,
  writeFileSync,
  rmSync,
} from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgDir = join(here, "..", "node_modules", "onnxruntime-web");
const src = join(pkgDir, "dist");

if (!existsSync(src)) {
  console.warn("[copy-ort-wasm] onnxruntime-web not installed yet, skipping");
  process.exit(0);
}

const version = JSON.parse(
  readFileSync(join(pkgDir, "package.json"), "utf8")
).version;

// Exactly the two files the plain-WASM backend asks for at runtime. The jsep
// (WebGPU), jspi and asyncify variants are another 71 MB between them and we
// use none of them -- on a 600 kB/s connection every unused megabyte in
// public/ is seconds of a farmer's time.
const WANTED = ["ort-wasm-simd-threaded.wasm", "ort-wasm-simd-threaded.mjs"];

const publicOrt = join(here, "..", "public", "ort");
const dest = join(publicOrt, version);

// Drop stale versions so public/ does not accumulate 14 MB per upgrade.
if (existsSync(publicOrt)) {
  for (const entry of readdirSync(publicOrt)) {
    if (entry !== version) rmSync(join(publicOrt, entry), { recursive: true, force: true });
  }
}

mkdirSync(dest, { recursive: true });
const present = new Set(readdirSync(src));
let n = 0;
for (const f of WANTED) {
  if (!present.has(f)) {
    console.warn(`[copy-ort-wasm] MISSING ${f} -- inference will fail at runtime`);
    continue;
  }
  copyFileSync(join(src, f), join(dest, f));
  n++;
}

writeFileSync(
  join(here, "..", "lib", "ort-version.ts"),
  `// GENERATED by scripts/copy-ort-wasm.mjs -- do not edit.\n` +
    `// Keeps the runtime wasm path in step with the installed package.\n` +
    `export const ORT_VERSION = ${JSON.stringify(version)};\n`,
  "utf8"
);

console.log(`[copy-ort-wasm] copied ${n}/${WANTED.length} files to public/ort/${version}/`);
